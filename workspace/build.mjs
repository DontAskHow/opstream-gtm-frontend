#!/usr/bin/env node
// Interactive GTM workspace builder. Reads snapshot JSON from --data, brand
// assets from --brand and (optionally) the HubSpot reconciliation export from
// --recon, and writes a static site to --out that works from file:// or via
// serve.mjs. Node 20, no dependencies, no network. No data lives in the repo.
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync, readdirSync, rmSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildData, parseExpect, figuresReport } from './lib/project.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'src');
const FONTS = join(HERE, '..', 'source', 'assets', 'fonts');
const MARKER = '.gtm-workspace-build';
const USAGE = 'Usage: node workspace/build.mjs --data <snapshot-dir> --brand <brand-dir> --out <output-dir> [--recon <recon-dir>] [--expect count=N,amount=N,weighted=N,holdCount=N,holdAmount=N]';

export function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const m = /^--(data|brand|out|recon|expect)(?:=(.*))?$/.exec(argv[i]);
    if (m) args[m[1]] = m[2] ?? argv[++i];
    else if (argv[i] === '--quiet') args.quiet = true;
    else throw new Error(`unknown argument ${argv[i]}\n${USAGE}`);
  }
  if (!args.data || !args.brand || !args.out) throw new Error(USAGE);
  return {
    data: resolve(args.data), brand: resolve(args.brand), out: resolve(args.out),
    recon: args.recon ? resolve(args.recon) : null, expect: parseExpect(args.expect), quiet: !!args.quiet,
  };
}

function readJson(dir, file, warn) {
  const p = join(dir, file);
  if (!existsSync(p)) {
    warn(`warn: ${file} not found in ${dir}; panels that use it show empty states`);
    return null;
  }
  return JSON.parse(readFileSync(p, 'utf8'));
}

// The meeting-prep file is found by its shape (a prep[] list and a brief),
// so its file name does not have to be written into this repo.
function findPrepFile(dir, warn) {
  for (const f of readdirSync(dir).sort()) {
    if (!f.endsWith('.json') || f === 'records.json') continue;
    const p = join(dir, f);
    if (statSync(p).size > 5e6) continue;
    try {
      const j = JSON.parse(readFileSync(p, 'utf8'));
      if (j && Array.isArray(j.prep) && j.brief && typeof j.brief === 'object') return j;
    } catch { /* not JSON we can use */ }
  }
  warn('warn: no meeting-prep file (a JSON with prep[] and brief) in the data dir; prep briefs show empty states');
  return null;
}

// Only clear an output directory this builder made (or an empty one).
function prepareOut(out) {
  if (existsSync(out)) {
    const entries = readdirSync(out);
    if (entries.length && !entries.includes(MARKER)) {
      throw new Error(`refusing to clear ${out}: it is not empty and was not written by this builder (no ${MARKER})`);
    }
    rmSync(out, { recursive: true, force: true });
  }
  mkdirSync(join(out, 'vendor'), { recursive: true });
  mkdirSync(join(out, 'fonts'), { recursive: true });
  writeFileSync(join(out, MARKER), 'Generated by workspace/build.mjs. Contains snapshot data: never commit.\n');
}

// Transcripts become one script file each, loaded on demand (a <script> tag
// works from file://; fetch does not).
const SAFE_ID = /^[A-Za-z0-9_-]+$/;
function writeTranscripts(dataDir, outDir, wanted) {
  const tDir = join(dataDir, 'transcripts');
  const available = [];
  if (!existsSync(tDir)) return available;
  mkdirSync(join(outDir, 'transcripts'), { recursive: true });
  for (const f of readdirSync(tDir).sort()) {
    const id = f.replace(/\.json$/, '');
    if (!f.endsWith('.json') || !SAFE_ID.test(id) || !wanted.has(id)) continue;
    const raw = JSON.parse(readFileSync(join(tDir, f), 'utf8'));
    const lines = (Array.isArray(raw) ? raw : []).map((l) => ({ s: l?.speaker ?? null, t: l?.timestamp ?? null, x: l?.text ?? null }));
    writeFileSync(join(outDir, 'transcripts', `${id}.js`),
      `window.GTM_TRANSCRIPT&&window.GTM_TRANSCRIPT(${JSON.stringify(id)},${safeJson(lines)});\n`);
    available.push(id);
  }
  return available;
}

// JSON is valid JS; escaping "<" means no string can close the script element.
const safeJson = (v) => JSON.stringify(v).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

export function build(opts) {
  const log = opts.quiet ? () => {} : (...a) => console.log(...a);
  const warn = opts.quiet ? () => {} : (...a) => console.warn(...a);
  const dir = opts.data;
  const inputs = {
    records: readJson(dir, 'records.json', warn),
    marketing: readJson(dir, 'marketing.json', warn),
    brief: readJson(dir, 'agent-brief.json', warn),
    sheetReview: readJson(dir, 'sheet-review.json', warn),
    operator: findPrepFile(dir, warn),
    expect: opts.expect,
  };
  if (opts.recon) {
    const p = join(opts.recon, 'live_deals.json');
    if (!existsSync(p)) throw new Error(`--recon ${opts.recon} has no live_deals.json`);
    // The export has no timestamp of its own; the file time is when it was fetched.
    inputs.recon = { live: JSON.parse(readFileSync(p, 'utf8')), fetchedAt: statSync(p).mtime.toISOString() };
  }

  prepareOut(opts.out);
  const wanted = new Set((inputs.records?.companies || []).flatMap((c) => (c.recordings || []).filter((r) => r.hasTranscript).map((r) => r.id)));
  inputs.transcripts = writeTranscripts(dir, opts.out, wanted);
  const data = buildData(inputs);

  writeFileSync(join(opts.out, 'data.js'), `window.GTM_DATA=${safeJson(data)};\n`);
  for (const f of ['index.html', 'app.js', 'styles.css']) copyFileSync(join(SRC, f), join(opts.out, f));
  copyFileSync(join(SRC, 'charts.js'), join(opts.out, 'vendor', 'gtm-charts.js'));
  for (const f of ['poppins-400.ttf', 'poppins-600.ttf']) {
    if (existsSync(join(FONTS, f))) copyFileSync(join(FONTS, f), join(opts.out, 'fonts', f));
    else warn(`warn: font ${f} not found; headings fall back to system fonts`);
  }
  const logo = join(opts.brand, 'logo-main.svg');
  if (existsSync(logo)) copyFileSync(logo, join(opts.out, 'logo.svg'));
  else warn('warn: logo-main.svg not found in the brand dir; the top bar shows the product name only');

  const q = data.quality;
  log(`wrote ${opts.out}`);
  log(`  ${data.companies.length} accounts, ${data.deals.length} deals, ${data.transcripts.length} transcripts`);
  log(figuresReport(data));
  const h = data.headline;
  const usd = (v) => '$' + Math.round(v).toLocaleString('en-US');
  log(h
    ? `headline (HubSpot, ${h.pipeline}): ${h.active.count} open deals excl On Hold, ${usd(h.active.openAmount)} open, ` +
      `${usd(h.active.weighted)} weighted; On Hold ${h.onHold.count} deals, ${usd(h.onHold.openAmount)}`
    : 'headline: none (build with --recon for the HubSpot headline)');
  if (h) {
    const e = data.expect;
    log(e.checked
      ? `  expected figures: ${e.matches ? 'MATCH' : 'MISMATCH'} (${e.rows.map((r) => `${r.key} ${r.got}${r.ok ? '' : ' != ' + r.want}`).join(', ')})`
      : '  expected figures: not given (--expect); the pipeline caveat stays on');
  }
  log(`  data quality: ${q.closedButActive.length} Sheet-active deals closed in HubSpot; ` +
    `${q.missingFromSheet == null ? 'missing-from-Sheet needs --recon' : q.missingFromSheet.length + ' open new-business HubSpot deals not on the Sheet'}; ` +
    `${q.otherDiffs.length} other Sheet/HubSpot stage differences; ${q.notInHubspot.length} Sheet-active rows not in HubSpot`);
  if (data.bridge != null) log(`  Sheet-active ${q.sheetActiveCount} → HubSpot bridge: ${data.bridge} (HubSpot count ${data.headline?.active.count})`);
  if (data.notInExport) log(`  ${data.notInExport} records.json deals are not in the HubSpot export`);
  return data;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    build(parseArgs(process.argv.slice(2)));
  } catch (err) {
    console.error(err.message);
    process.exit(2);
  }
}
